"""Reproduce C1 timings/cost cache: python -m experiments.core_benchmark.

Writes results/core_benchmark.json. --refresh-costs regenerates the packaged
representative cost cache from the circuits, never from hand-entered estimates.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import statistics
import subprocess
import sys
from time import perf_counter

import swapprint as sp


def _measure(fn, repeats):
    times = []
    result = None
    for _ in range(repeats):
        start = perf_counter()
        result = fn()
        times.append(perf_counter() - start)
    return statistics.median(times), result


def main():
    from qiskit import transpile, __version__ as qiskit_version
    from qiskit_aer import __version__ as aer_version

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-costs", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    image_a, image_b = sp.synthetic.artwork(2026), sp.synthetic.artwork(2027)
    pairs = {mode: (sp.fingerprint(image_a, mode), sp.fingerprint(image_b, mode))
             for mode in ("strict", "perceptual", "frqi")}
    report = dict(qiskit=qiskit_version, qiskit_aer=aer_version, seed=2026, shots=1024,
                  hardware_basis=["cx", "rz", "sx", "x"], optimization_level=3,
                  hardware=[], q11=[], compare=[])
    costs = {}
    for mode, (a, b) in pairs.items():
        for kind in ("ancilla", "destructive"):
            qc = sp.circuits.swap_test(a, b, 0, kind)
            start = perf_counter()
            isa = transpile(qc, basis_gates=report["hardware_basis"], optimization_level=3, seed_transpiler=2026)
            seconds = perf_counter() - start
            cost = (sum(i.operation.num_qubits == 2 for i in isa.data), isa.depth())
            costs[mode, kind, a.q] = cost
            row = dict(mode=mode, kind=kind, q=a.q, two_qubit_gates=cost[0], depth=cost[1], seconds=seconds)
            if mode == "strict":
                warm, _ = _measure(lambda: transpile(qc, basis_gates=report["hardware_basis"],
                                                     optimization_level=3, seed_transpiler=2026), 3)
                row["warm_seconds_median"] = warm
            report["hardware"].append(row)
            print("hardware", row, flush=True)
    if args.refresh_costs:
        header = '''"""Cached representative hardware costs (CX count, total depth).

Generated by python -m experiments.core_benchmark --refresh-costs with Qiskit
2.6.1: fingerprints of synthetic.artwork(2026) vs synthetic.artwork(2027), unit 0.
Basis [cx, rz, sx, x], all-to-all, optimization_level=3, seed_transpiler=2026.
These approximate other units; generic diagonal CX counts depend slightly on
the signs. The first q=11 cost transpile took ~3 s (warm ~0.25 s), so the
canonical per-(mode, kind) costs are computed once and persisted here.
"""
COSTS = {
'''
        entries = "".join(f"    {key!r}: {value!r},\n" for key, value in costs.items())
        (root / "swapprint" / "_hardware_costs.py").write_text(header + entries + "}\n", encoding="utf-8")
    a, b = pairs["strict"]
    for kind in ("ancilla", "destructive"):
        prep, _ = _measure(lambda: sp.circuits.state_circuit(a, 0), 20)
        build, _ = _measure(lambda: sp.circuits.swap_test(a, b, 0, kind), 20)
        run, result = _measure(lambda: sp.circuits.run_swap_test(a, b, 0, kind=kind, seed=2026), 3)
        # Isolated process: time the first call, including lazy Qiskit/Aer imports.
        code = ("import json,time,swapprint as sp; "
                "a=sp.fingerprint(sp.synthetic.artwork(2026)); "
                "b=sp.fingerprint(sp.synthetic.artwork(2027)); "
                "t=time.perf_counter(); "
                f"r=sp.circuits.run_swap_test(a,b,0,kind={kind!r},seed=2026); "
                "print(json.dumps({'seconds':time.perf_counter()-t,'aer_seconds':r['seconds']}))")
        cold = json.loads(subprocess.run([sys.executable, "-c", code], cwd=root, text=True,
                                         capture_output=True, check=True).stdout)
        row = dict(kind=kind, state_circuit_seconds=prep, swap_test_seconds=build,
                   run_swap_test_seconds=run, aer_seconds_last=result["seconds"],
                   cold_call_seconds=cold["seconds"], cold_aer_seconds=cold["aer_seconds"])
        report["q11"].append(row)
        print("q11", row, flush=True)
        elapsed, comparison = _measure(lambda: sp.compare(a, b, backend="aer", kind=kind, seed=2026), 1)
        report["compare"].append(dict(kind=kind, seconds=elapsed, circuit_tiles=comparison.circuit_tiles))
        print("compare", report["compare"][-1], flush=True)
    output = root / "experiments" / "results" / "core_benchmark.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
